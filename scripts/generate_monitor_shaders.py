def find_glslang(path):
    if path:
        return path
    found = shutil.which('glslangValidator')
    if found:
        return found
    sdk = os.environ.get('VULKAN_SDK')
    if sdk:
        for name in ('glslangValidator', 'glslangValidator.exe'):
            for bin_dir in ('Bin', 'bin'):
                candidate = os.path.join(sdk, bin_dir, name)
                if os.path.isfile(candidate):
                    return candidate
    sys.exit('glslangValidator not found. Install the Vulkan SDK or pass --glslang.')


def glslang_version(glslang):
    output = subprocess.run([glslang, '--version'], capture_output=True, text=True, check=True).stdout
    lines = output.splitlines()
    for line in lines:
        if line.startswith('Glslang Version'):
            return line.strip()
    return lines[0].strip() if lines else 'Glslang Version: unknown'


def compile_shader(glslang, source, out_dir):
    spv = os.path.join(out_dir, os.path.basename(source) + '.spv')
    result = subprocess.run([glslang, '-V', '--target-env', 'vulkan1.0', source, '-o', spv], capture_output=True, text=True)
    if result.returncode != 0:
        sys.exit(result.stdout + result.stderr)
    with open(spv, 'rb') as f:
        data = f.read()
    return struct.unpack('<%dI' % (len(data) // 4), data)


def source_hash(paths):
    """FNV-1a over the shader sources with carriage returns dropped, so CRLF checkouts hash the same.
    test_monitor_overlay recomputes it to catch shaders changed without regenerating this header."""
    value = 0xcbf29ce484222325
    for path in paths:
        with open(path, 'rb') as f:
            for byte in f.read().replace(b'\r', b''):
                value = ((value ^ byte) * 0x100000001b3) & 0xFFFFFFFFFFFFFFFF
    return value


def format_array(name, words):
    lines = ['inline constexpr std::array<uint32_t, %d> %s = {' % (len(words), name)]
    for i in range(0, len(words), 8):
        lines.append('    ' + ', '.join('0x%08x' % w for w in words[i:i + 8]) + ',')
    lines.append('};')
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description='Generate the monitor layer overlay SPIR-V header.')
    parser.add_argument('--glslang', help='Path to glslangValidator')
    args = parser.parse_args()

    glslang = find_glslang(args.glslang)
    parts = [HEADER.format(version=glslang_version(glslang))]
    sources = [os.path.join(SHADER_DIR, source) for source, _ in SHADERS]
    parts.append('// Hash of the shader sources this was generated from\ninline constexpr uint64_t kMonitorOverlayShaderSourceHash = 0x%016xull;\n'
                 % source_hash(sources))
    with tempfile.TemporaryDirectory() as out_dir:
        for source, name in SHADERS:
            words = compile_shader(glslang, os.path.join(SHADER_DIR, source), out_dir)
            parts.append('// %s\n%s\n' % (source, format_array(name, words)))

    with open(OUTPUT, 'w', newline='\n') as f:
        f.write('\n'.join(parts))


if __name__ == '__main__':
    main()

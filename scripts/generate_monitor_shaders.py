# Compiles the monitor layer overlay shaders to SPIR-V and writes them to
# layersvt/monitor_overlay_shaders.h. The header is checked in, so building the
# layer doesn't need glslang. Run this after changing layersvt/shaders/*.
#
# Usage: python3 scripts/generate_monitor_shaders.py [--glslang <path to glslangValidator>]

